/* 3주차 흐름도. 원본 노션 글의 플로우차트를 행으로 옮겼다. 칸 표시: h = 사람이 하는 일, r = 검증·점검 단계 */
function flows(boxId, sayId, rows) {
  const box = $(boxId), say = $(sayId);
  const btns = rows.map(([when, sub, chain, text], i) => {
    const b = h('button', 'frow2');
    b.type = 'button';
    b.innerHTML = `<span class="lab"><b>${when}</b><span>${sub}</span></span><span class="chain">${chain.map(([t, k]) => `<i class="${k || ''}">${t}</i>`).join('<em>→</em>')}</span>`;
    b.addEventListener('click', () => pick(i));
    box.appendChild(b);
    return b;
  });
  function pick(i) {
    btns.forEach((b, j) => b.setAttribute('aria-pressed', j === i ? 'true' : 'false'));
    say.textContent = rows[i][3];
  }
  pick(rows.length - 1);
}

